def missing(items, example):
    """信息缺失模板"""
    lines = ["【🐷 指令缺少信息】"]
    if isinstance(items, (list, tuple)):
        for it in items:
            if it:
                lines.append(f"· {it}")
    elif items:
        lines.append(f"· {items}")
    if example:
        lines.append(f"· 示例：{example}")
    return "\n".join(lines)


def invalid(reason, example=""):
    """参数非法模板"""
    lines = ["【🐷 指令无法执行】", f"· {reason}"]
    if example:
        lines.append(f"· 示例：{example}")
    return "\n".join(lines)


