def summarize_user(title, text):
    """概括请求的用户提示词"""
    body = text[:6000]
    return f"书名：{title}\n刚读到的内容：\n{body}\n\n请概括以上内容。"


def judge_user(title, text):
    """续读判定的用户提示词"""
    return f"正在读的书：{title}\n用户新消息：{text}\n请判断是否想继续读。"
